package neiro.simple.net.loss;


import neiro.simple.net.Tensor;

/**
 * Интерфейс функции потерь.
 */
public interface Loss {

    /**
     * Вычислить значение функции потерь.
     *
     * @param predicted предсказания модели
     * @param target    истинные значения
     * @return скалярное значение (среднее по батчу)
     */
    float compute(Tensor predicted, Tensor target);

    /**
     * Вычислить градиент функции потерь по предсказаниям.
     *
     * @param predicted предсказания модели
     * @param target    истинные значения
     * @return тензор градиентов той же формы, что и predicted
     */
    Tensor gradient(Tensor predicted, Tensor target);
}

/*
Рекомендации по выбору функции потерь
1. Категориальная кросс-энтропия (CategoricalCrossEntropyLoss)
Когда использовать: многоклассовая классификация с взаимоисключающими классами (например, MNIST, CIFAR-10, классификация изображений).

Особенности: требует Softmax на последнем слое. Хорошо работает при сбалансированных данных.

Совет: используйте LabelSmoothing (можно реализовать как модификацию) для регуляризации.

2. Бинарная кросс-энтропия (BinaryCrossEntropyLoss)
Когда использовать: бинарная классификация или многоклассовая с мульти-лейблами (например, наличие нескольких тегов у изображения). Последний слой – Sigmoid.

Совет: если классы сильно несбалансированы, добавьте веса (pos_weight).

3. Mean Squared Error (MSE) – рекомендуем добавить
Когда использовать: регрессия (предсказание цены, координат, возраста). Также как вспомогательная функция в автоэнкодерах.

Нюанс: чувствительна к выбросам – для робастности лучше использовать Huber Loss.

4. Huber Loss – рекомендуем добавить
Когда использовать: регрессия с выбросами (например, предсказание GPS-координат, финансовые временные ряды).

Преимущество: не взрывает градиент при больших ошибках.

5. NegativeSamplingWithEmbeddingLoss (уже есть)
Когда использовать: очень большое количество классов (сотни тысяч и миллионы), когда полный softmax невозможен. Классический пример – word2vec, рекомендательные системы.

Требование: модель возвращает эмбеддинг (скрытый вектор), а loss содержит матрицу эмбеддингов классов.

6. Focal Loss – рекомендуем добавить
Когда использовать: задачи с сильным дисбалансом классов (детекция редких объектов, медицинская диагностика, мошенничество).

Пример: один класс составляет 1% выборки – Focal Loss с γ=2 даёт прирост точности.

7. Contrastive Loss / Triplet Loss – добавить при необходимости
Когда использовать: метрическое обучение (поиск похожих лиц, дубликатов, рекомендации). Требует специальной организации батчей.

Сложность: нужна пара/триплетная выборка.

8. KL Divergence – добавить для вероятностных моделей
Когда использовать: дистилляция знаний (обучение маленькой модели имитировать большую), вариационные автоэнкодеры (VAE), моделирование распределений.

9. Poisson Loss (можно добавить)
Когда использовать: подсчёт событий (количество звёзд на фото, количество кликов). Выходное распределение Пуассона.

10. Для ранжирования (если потребуется)
ListNet Loss, LambdaRank – для поисковых систем, рекомендаций с фидбеком.

Общий чек-лист выбора
Задача	Рекомендуемая функция потерь
Классификация (сбалансированные классы)	CategoricalCrossEntropyLoss
Классификация (дисбаланс)	FocalLoss (γ=2) или WeightedCrossEntropy
Бинарная классификация (дисбаланс)	BinaryCrossEntropyLoss с pos_weight либо FocalLoss (бинарный)
Мульти-лейбл (несколько правильных ответов)	BinaryCrossEntropyLoss (каждый класс независимо)
Регрессия (обычная)	MSELoss
Регрессия с выбросами	HuberLoss (delta=1.0)
Миллионы классов	NegativeSamplingWithEmbeddingLoss
Обучение эмбеддингов / сиамские сети	ContrastiveLoss или TripletLoss
Дистилляция / VAE	KLDivergenceLoss
Подсчёт событий	PoissonLoss
 */